"use client";
import * as React from "react";
import Link from "next/link";
import { useRouter, useSearchParams } from "next/navigation";
import { toast } from "sonner";
import { CodeInput, ResendCodeButton, emptyCode, type CodeInputHandle } from "@/components/onboarding/code-input";
import { CheckingOverlay, Field, fieldCls } from "@/components/onboarding/frame";
import { ForenButton } from "@/components/ui/foren-button";
import { ForenSpinner } from "@/components/ui/foren-spinner";
import { useLogin } from "@/lib/login-store";
import { cn } from "@/lib/utils";
import { AuthArt, AuthFrame, AuthHeading, PrototypeHint, textLinkCls } from "./auth-frame";

/**
 * Two-factor step after the password (Figma 8751:110498 authenticator app, 8751:110540 code sent by
 * email, 8751:110583 / 8751:110624 backup code). `?method=email` and `?method=backup` pick the variant.
 */
type Method = "app" | "email" | "backup";

const WRONG_CODE = "000000";

export function LoginVerify() {
  const router = useRouter();
  const params = useSearchParams();
  const method: Method = params.get("method") === "email" ? "email" : params.get("method") === "backup" ? "backup" : "app";
  const identifier = useLogin((s) => s.identifier);

  // Straight here without logging in: start at the login form.
  React.useEffect(() => {
    if (!identifier) router.replace("/login");
  }, [identifier, router]);
  if (!identifier) return null;

  const done = () => {
    toast.success("You’re logged in");
    router.push("/cards");
  };

  return (
    <AuthFrame>
      <div className="flex flex-col gap-[45px]">
        <AuthArt src="/login/lock.png" size={100} />
        {method === "backup" ? (
          <BackupCode onDone={done} />
        ) : (
          <CodeStep key={method} method={method} identifier={identifier} onDone={done} />
        )}
      </div>
    </AuthFrame>
  );
}

function CodeStep({ method, identifier, onDone }: { method: "app" | "email"; identifier: string; onDone: () => void }) {
  const [digits, setDigits] = React.useState<string[]>(emptyCode);
  const [error, setError] = React.useState<string | null>(null);
  const [checking, setChecking] = React.useState(false);
  const codeRef = React.useRef<CodeInputHandle>(null);
  // After a wrong code the boxes are cleared and re-enabled: put the cursor back in the first one.
  React.useEffect(() => {
    if (error && !checking && digits.every((d) => !d)) codeRef.current?.focus(0);
  }, [error, checking, digits]);

  const verify = (code: string) => {
    setChecking(true);
    setError(null);
    setTimeout(() => {
      if (code === WRONG_CODE) {
        setChecking(false);
        setError(method === "app" ? "That code isn’t right. Enter the latest code from your authenticator app." : "That code isn’t right. Check the latest code we sent, or resend it.");
        setDigits(emptyCode());
        return;
      }
      onDone();
    }, 1000);
  };

  const onDigitsChange = (next: string[]) => {
    setDigits(next);
    setError(null);
    // The emailed code checks itself once complete (no Verify button in Figma); the app code waits for Verify.
    if (method === "email" && next.every((d) => d)) verify(next.join(""));
  };

  const submit = (e: React.FormEvent) => {
    e.preventDefault();
    const firstEmpty = digits.findIndex((d) => !d);
    if (firstEmpty >= 0) {
      setError("Enter the 6-digit code");
      codeRef.current?.focus(firstEmpty);
      return;
    }
    verify(digits.join(""));
  };

  const hintId = `login-code-${method}-hint`;

  return (
    <>
      <AuthHeading title="Verify your identity">
        {method === "app" ? (
          <p>
            Enter the code generated by your <span className="text-fg">authenticator app</span>
          </p>
        ) : (
          <p>
            Enter the 6-digit code sent to <span className="break-all text-fg">{identifier}</span>
          </p>
        )}
      </AuthHeading>

      {method === "app" ? (
        <form noValidate onSubmit={submit} className="flex flex-col items-center gap-8 rounded-[24px] bg-surface px-4 py-6">
          <div className="flex min-h-[111px] w-full flex-col items-center justify-center gap-2">
            <CodeInput ref={codeRef} digits={digits} onDigitsChange={onDigitsChange} disabled={checking} invalid={!!error} autoFocus describedBy={error ? hintId : undefined} />
            {error && (
              <p id={hintId} role="alert" className="text-center text-[12px] leading-[18px] font-medium tracking-[0.01em] text-error">
                {error}
              </p>
            )}
          </div>
          <ForenButton
            type="submit"
            className="w-full"
            disabled={checking}
            aria-busy={checking || undefined}
            leadingIcon={checking ? <ForenSpinner size="sm" className="text-current" /> : undefined}
          >
            Verify
          </ForenButton>
          <Link href="/login/verify?method=backup" className={textLinkCls}>
            Use Backup Code
          </Link>
        </form>
      ) : (
        <div className="flex flex-col items-center gap-8 rounded-[24px] bg-surface px-4 py-6">
          <div className="flex flex-col items-center gap-[26px]">
            <CodeInput ref={codeRef} digits={digits} onDigitsChange={onDigitsChange} disabled={checking} invalid={!!error} autoFocus describedBy={hintId} />
            <p id={hintId} role={error ? "alert" : undefined} className={cn("text-center text-[12px] leading-[18px] font-medium tracking-[0.01em]", error ? "text-error" : "text-fg-3")}>
              {error ?? "Didn’t get it? Check spam, or resend below."}
            </p>
          </div>
          <ResendCodeButton disabled={checking} onResend={() => toast(`We sent a new code to ${identifier}`)} />
          {checking && <CheckingOverlay label="Checking your code" />}
        </div>
      )}

      <PrototypeHint className="-mt-6 text-center">
        Prototype: any 6 digits work. 000000 shows the error.{" "}
        {method === "app" ? (
          <Link href="/login/verify?method=email" className="underline underline-offset-2">
            Try the emailed code instead
          </Link>
        ) : (
          <Link href="/login/verify" className="underline underline-offset-2">
            Try the authenticator app instead
          </Link>
        )}
      </PrototypeHint>
    </>
  );
}

/** Backup codes are long letters-and-numbers strings (Figma example: 211MXLRGH8990933EEW). */
const BACKUP_RE = /^[A-Z0-9]{10,24}$/;

function BackupCode({ onDone }: { onDone: () => void }) {
  const [code, setCode] = React.useState("");
  const [error, setError] = React.useState<string | null>(null);
  const [checking, setChecking] = React.useState(false);
  const ref = React.useRef<HTMLInputElement>(null);

  const submit = (e: React.FormEvent) => {
    e.preventDefault();
    const clean = code.replace(/[\s-]/g, "").toUpperCase();
    if (!BACKUP_RE.test(clean)) {
      setError("Enter a valid backup code. It’s 10 to 24 letters and numbers.");
      ref.current?.focus();
      return;
    }
    setChecking(true);
    setTimeout(onDone, 900);
  };

  return (
    <>
      <AuthHeading title="Verify your identity with backup code">
        <p>Enter your authenticator app backup code</p>
      </AuthHeading>
      <form noValidate onSubmit={submit} className="flex flex-col gap-6 rounded-[24px] bg-surface px-4 py-6">
        <Field label="Enter backup code" htmlFor="login-backup" error={error}>
          <input
            ref={ref}
            id="login-backup"
            autoComplete="one-time-code"
            autoCapitalize="characters"
            spellCheck={false}
            autoFocus
            value={code}
            aria-invalid={!!error || undefined}
            onChange={(e) => {
              setCode(e.target.value);
              setError(null);
            }}
            className={cn(fieldCls, "uppercase placeholder:normal-case")}
          />
        </Field>
        <ForenButton
          type="submit"
          className="w-full"
          disabled={!code.trim() || checking}
          aria-busy={checking || undefined}
          leadingIcon={checking ? <ForenSpinner size="sm" className="text-current" /> : undefined}
        >
          Verify
        </ForenButton>
        <Link href="/login/verify" className={cn(textLinkCls, "self-start")}>
          Return to login with code from authenticator app
        </Link>
      </form>
      <PrototypeHint className="-mt-6 text-center">Prototype: any 10 to 24 letters and numbers work, like 211MXLRGH8990933EEW.</PrototypeHint>
    </>
  );
}
